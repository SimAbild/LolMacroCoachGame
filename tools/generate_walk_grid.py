"""Generates src/data/walkGrid.js from Riot's Summoner's Rift minimap (Data Dragon map11.png).

Usage (PowerShell):  python tools/generate_walk_grid.py path/to/map11.png
"""
import sys
from pathlib import Path

from PIL import Image

GRID_SIZE = 128
WALKABLE_BRIGHTNESS = 60
WALKABLE_SHARE = 0.5
OUTPUT_FILE = Path(__file__).resolve().parent.parent / 'src' / 'data' / 'walkGrid.js'


def is_walkable_pixel(pixel):
    return max(pixel) > WALKABLE_BRIGHTNESS


def build_rows(image):
    cell_size = image.width / GRID_SIZE
    rows = []
    for row in range(GRID_SIZE):
        cells = []
        for column in range(GRID_SIZE):
            left, top = int(column * cell_size), int(row * cell_size)
            right, bottom = int((column + 1) * cell_size), int((row + 1) * cell_size)
            pixels = [image.getpixel((x, y)) for x in range(left, right) for y in range(top, bottom)]
            walkable_share = sum(is_walkable_pixel(pixel) for pixel in pixels) / len(pixels)
            cells.append('.' if walkable_share >= WALKABLE_SHARE else '#')
        rows.append(''.join(cells))
    return rows


def main():
    image = Image.open(sys.argv[1]).convert('RGB')
    rows = build_rows(image)
    lines = [
        '// Generated by tools/generate_walk_grid.py from Data Dragon map11.png. "." = walkable, "#" = wall.',
        f'export const WALK_GRID_SIZE = {GRID_SIZE};',
        '',
        'export const WALK_GRID_ROWS = Object.freeze([',
        *[f"  '{row}'," for row in rows],
        ']);',
        '',
    ]
    OUTPUT_FILE.write_text('\n'.join(lines), encoding='utf-8')
    print(f'Wrote {OUTPUT_FILE}')


if __name__ == '__main__':
    main()
